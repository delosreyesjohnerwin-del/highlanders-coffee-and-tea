/// Firestore collection and document naming.
///
/// Every path in the app goes through this file. The reason is not tidiness:
/// the security rules in `firestore.rules` name the same collections, and a
/// typo in a collection name does not fail loudly — it writes to an orphan
/// collection that no rule governs, and the catch-all at the bottom of the rules
/// denies reads on it. The document disappears rather than erroring.
///
/// The catch-all is the reason the tests in `firestore_rules_test.dart` probe an
/// undeclared collection and expect a 403.
class FirestorePaths {
  const FirestorePaths._();

  /// Menu items. Readable by anyone, written by admins.
  static const String menuItems = 'menuItems';

  /// Menu categories ("Coffee", "Brews"). Readable by anyone.
  static const String menuCategories = 'menuCategories';

  /// Promotional banners. Readable by anyone.
  static const String promos = 'promos';

  /// Shop configuration. A single well-known document rather than a collection
  /// of versions — see [settingsDoc].
  static const String settings = 'settings';

  /// Orders from customers. The only collection with per-customer rules.
  static const String orders = 'orders';

  /// Staff roster: baristas, riders, managers.
  static const String staffMembers = 'staffMembers';

  /// Attendance log: one document per clock-in or clock-out.
  ///
  /// A flat collection with a `staffId` field rather than a subcollection under
  /// the staff document. The panel reads one member's history with an equality
  /// filter, which is the shape the rules and the rest of this layer already
  /// use, and it keeps every collection name in one flat list to audit.
  static const String shiftEvents = 'shiftEvents';

  /// Staff attendance sessions: one document per shift, opened by a clock-in and
  /// closed by the matching clock-out.
  ///
  /// Distinct from [shiftEvents]: that collection is the append-only transition
  /// log behind one member's "Recent shifts" timeline, while this is the mutable
  /// session row the Staff Record table prints. A session is updated in place on
  /// clock-out, which a transition event can never be.
  static const String staffRecords = 'staffRecords';

  /// Saved delivery addresses. Keyed by uid.
  static const String addresses = 'addresses';

  /// Linked payment methods. Keyed by uid.
  static const String paymentMethods = 'paymentMethods';

  /// Cached Xendit customer mapping, keyed by uid.
  ///
  /// Written **only** by the `linkPaymentMethod` Cloud Function via the admin
  /// SDK (it maps each app user to a Xendit `Customer` so reusable payment
  /// methods attach to the right vault). Clients never read or write it; the
  /// rules block denies everything.
  static const String paymentGatewayCustomers = 'paymentGatewayCustomers';

  /// FCM device registrations, keyed by the device token itself.
  ///
  /// Written by the app when a signed-in user grants notification permission
  /// (one document per device, uid-scoped) and read by the `onOrderCreated` /
  /// `onOrderUpdated` Cloud Functions via the admin SDK to find the tokens to
  /// push to. A re-registration overwrites the document, so signing into a
  /// second account on the same device simply rewrites `uid`.
  static const String notificationTokens = 'notificationTokens';

  /// The one shop-settings document id.
  ///
  /// A single id means the app reads one document instead of running a
  /// `where('shopId', ==)` query for a shop that will never be more than one
  /// shop. Public read is allowed on `settings`, so a signed-out customer still
  /// sees the correct opening hours.
  static const String settingsDoc = 'highlanders';

  /// Address document ids are user-scoped, so two customers cannot collide on
  /// the same autogenerated id.
  static String addressDoc(String uid, String addressId) => '${uid}_$addressId';

  /// Payment-method document ids are user-scoped for the same reason as
  /// [addressDoc]: a customer links "my GCash", and another linking their own
  /// GCash must not overwrite it.
  static String paymentMethodDoc(String uid, String accountId) => '${uid}_$accountId';

  /// Staff document ids are the staff member's own slug.
  static String staffDoc(String staffId) => staffId;

  /// Shift-event document ids are minted by the client
  /// ([mintShiftEventId]) so both the Firestore and in-memory repositories key
  /// on the same value.
  static String shiftEventDoc(String eventId) => eventId;

  /// Staff-record document ids are minted by the client
  /// ([mintStaffRecordId]) for the same reason as [shiftEventDoc].
  static String staffRecordDoc(String recordId) => recordId;
}